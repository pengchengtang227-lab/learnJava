-- CHECK 约束是数据库层的最后一道保护：账户余额不能为负数。
CREATE TABLE account (
    id BIGINT PRIMARY KEY,
    owner VARCHAR(50) NOT NULL,
    balance_in_cents BIGINT NOT NULL CHECK (balance_in_cents >= 0)
);

-- 外键保证转账涉及的账户真实存在，金额必须为正且不能给自己转账。
CREATE TABLE transfer_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_account_id BIGINT NOT NULL REFERENCES account(id),
    to_account_id BIGINT NOT NULL REFERENCES account(id),
    amount_in_cents BIGINT NOT NULL CHECK (amount_in_cents > 0),
    CHECK (from_account_id <> to_account_id)
);
